import sys, re, json, subprocess
from playwright.sync_api import sync_playwright
BASE = sys.argv[1]; PW = sys.argv[2]
errs = []
def ok(c, m):
    print(('PASS ' if c else 'FAIL ') + m)
    if not c: errs.append(m)

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(bypass_csp=True, viewport={'width':1366,'height':900}, locale='ar-EG')
    # ---- الموقع ----
    site = ctx.new_page()
    logs = []
    site.on('console', lambda m: logs.append(m.text) if m.type=='error' else None)
    site.on('pageerror', lambda e: logs.append('PAGEERROR '+str(e)))
    site.goto(BASE + '/')
    ok('120 - 140' in site.content(), 'website shows DB prices')
    site.wait_for_timeout(2600)
    site.fill('#fullName', 'سارة محمود')
    site.fill('#phoneNumber', '٠١٢٣٤٥٦٧٨٩٠')
    site.fill('#addressDetails', 'حدائق أكتوبر مجاورة 3 عمارة 5')
    site.select_option('#serviceType', 'carpet')
    site.click('.submit-btn')
    site.wait_for_selector('#confirmationModal.open', timeout=5000)
    ok(site.inner_text('#modalCustomerName') == 'سارة محمود', 'website modal after submit')
    site.screenshot(path='shots/site-modal.png')
    site.click('#modalConfirmBtn')
    # invalid phone
    site.fill('#fullName', 'x y'); site.fill('#phoneNumber', '123'); site.fill('#addressDetails','عنوان طويل جدا'); site.select_option('#serviceType','all')
    site.click('.submit-btn')
    ok(site.inner_text('[data-for=phoneNumber]') != '', 'website phone validation message')
    site.screenshot(path='shots/site-top.png', full_page=False)
    site.set_viewport_size({'width':390,'height':800})
    site.click('#hamburger')
    ok(site.get_attribute('#hamburger','aria-expanded') == 'true', 'hamburger aria-expanded')
    site.screenshot(path='shots/site-mobile.png')
    # ---- الكاشير ----
    page = ctx.new_page()
    cl = []
    page.on('console', lambda m: cl.append(m.text) if m.type=='error' else None)
    page.on('pageerror', lambda e: cl.append('PAGEERROR '+str(e)))
    page.goto(BASE + '/app/')
    page.fill('#login-username', 'admin'); page.fill('#login-password', 'wrong-pass-1')
    page.click('#login-form button[type=submit]')
    page.wait_for_function("document.querySelector('#login-error').textContent.length>0")
    ok('غير صحيحة' in page.inner_text('#login-error'), 'bad login message')
    page.fill('#login-password', PW)
    page.click('#login-form button[type=submit]')
    page.wait_for_selector('#password-dialog[open]')
    ok(not page.is_visible('#pw-close'), 'forced password: no close')
    page.fill('#pw-new', 'abc'); page.fill('#pw-confirm', 'abc'); page.click('#password-form button[type=submit]')
    page.wait_for_function("document.querySelector('#pw-error').textContent.length>0")
    page.fill('#pw-new', 'Laundry2026ok'); page.fill('#pw-confirm', 'Laundry2026ok'); page.click('#password-form button[type=submit]')
    page.wait_for_selector('#dashboard.active')
    page.wait_for_timeout(500)
    ok(page.is_visible('#requests-badge') and page.inner_text('#requests-badge').strip() != '', 'requests badge visible')
    page.screenshot(path='shots/dash.png')
    # requests
    page.click('[data-view=requests]')
    page.wait_for_selector('#requests-table [data-rconvert]')
    page.screenshot(path='shots/requests.png')
    page.click('#requests-table [data-rconvert]')
    page.wait_for_selector('#pos.active .selected-customer')
    ok('سارة' in page.inner_text('#selected-customer'), 'convert selects customer in POS')
    # add services
    page.click('[data-cat]:nth-child(3)')
    page.click('#service-options .chip >> nth=0')
    page.click('#service-cats [data-cat]:nth-child(1)')
    page.fill('#service-search', 'سجاد صوف')
    page.click('#add-service')
    page.fill('#service-search', 'شيفون'); page.click('#add-service')
    page.select_option('#zone', index=1)
    page.fill('#paid', '50')
    page.screenshot(path='shots/pos.png', full_page=True)
    page.click('#save-order')
    page.wait_for_selector('#invoice-dialog[open]')
    ok('4S-1001' in page.inner_text('#invoice-title'), 'order saved & invoice open')
    page.screenshot(path='shots/invoice.png')
    page.keyboard.press('Escape')
    # orders
    page.click('[data-view=orders]')
    page.wait_for_selector('#orders-table [data-next]')
    ok('بانتظار القياس' in page.inner_text('#orders-table'), 'order pending measure')
    page.click('#orders-table [data-next]')
    page.wait_for_selector('#measure-dialog[open]')
    for i in range(page.locator('#measure-fields input').count()): page.locator('#measure-fields input').nth(i).fill('7.5')
    page.screenshot(path='shots/measure.png')
    page.click('#measure-form button[type=submit]')
    page.wait_for_function("!document.querySelector('#measure-dialog').open")
    page.wait_for_timeout(400)
    ok('تحت التنفيذ' in page.inner_text('#orders-table'), 'status in progress after measure')
    page.click('#orders-table [data-next]'); page.wait_for_timeout(500)
    ok('جاهز للتسليم' in page.inner_text('#orders-table'), 'status ready')
    page.click('#orders-table [data-next]'); page.click('#confirm-ok'); page.wait_for_timeout(500)
    ok('تم التسليم' in page.inner_text('#orders-table'), 'status delivered')
    # customers: payment
    page.click('[data-view=customers]')
    page.wait_for_selector('#customer-table [data-pay]')
    page.click('#customer-table [data-pay]')
    page.select_option('#pay-method', 'instapay')
    page.click('#payment-form button[type=submit]')
    page.wait_for_timeout(600)
    ok(page.locator('#customer-table [data-pay]').count() == 0, 'balance cleared after payment')
    page.screenshot(path='shots/customers.png')
    # settings
    page.click('[data-view=settings]')
    page.wait_for_selector('#services-table tr')
    page.screenshot(path='shots/settings.png')
    page.click('[data-sedit] >> nth=0')
    page.fill('#sv-min', '125'); page.fill('#sv-max', '145')
    page.click('#service-form button[type=submit]')
    page.wait_for_timeout(600)
    page.click('[data-stab=users]'); page.wait_for_selector('#users-table tr')
    page.click('#add-user-btn'); page.fill('#u-username','cashier1'); page.fill('#u-name','موظفة الكاشير'); page.click('#user-form button[type=submit]')
    page.wait_for_selector('#temp-dialog[open]')
    temp = page.inner_text('#tp-pass'); ok(len(temp) >= 10, 'temp password shown')
    page.screenshot(path='shots/temp.png')
    page.click('#temp-dialog [data-close]')
    page.click('[data-stab=system]'); page.wait_for_selector('#audit-table tr td')
    page.click('[data-stab=business]'); page.screenshot(path='shots/business.png')
    site.set_viewport_size({'width':1366,'height':900}); site.reload()
    ok('125 - 145' in site.content(), 'website reflects new price')
    # logout/login again, session survives reload
    page.reload(); page.wait_for_selector('#settings.active, #dashboard.active')
    ok(page.is_hidden('#login-screen'), 'session persists across reload')
    page.click('#logout'); page.wait_for_selector('#login-screen:not(.hidden)')
    # cashier role
    page.fill('#login-username','cashier1'); page.fill('#login-password', temp)
    page.click('#login-form button[type=submit]'); page.wait_for_selector('#password-dialog[open]')
    page.fill('#pw-new','Cashier2026ok'); page.fill('#pw-confirm','Cashier2026ok'); page.click('#password-form button[type=submit]')
    page.wait_for_selector('#dashboard.active')
    page.wait_for_function("document.querySelector('#current-user').textContent.includes('موظفة')")
    ok(page.is_hidden('[data-view=settings]'), 'cashier cannot see settings')
    page.screenshot(path='shots/cashier-dash.png')
    # mobile
    page.set_viewport_size({'width':390,'height':844}); page.click('#menu-toggle'); page.click('[data-view=orders]'); page.wait_for_timeout(500)
    page.screenshot(path='shots/mobile-orders.png')
    real = [l for l in logs+cl if 'fonts' not in l and 'ERR_' not in l and 'Failed to load resource' not in l]
    ok(not real, 'no console errors: ' + str(real[:5]))
    b.close()
print('FAILED' if errs else 'ALL OK')
sys.exit(1 if errs else 0)
